def test_every_released_name_resolves():
    unresolvable = sorted(n for n in RELEASED_SIGNAL_NAMES if not RuleRegistry.has(n))
    assert not unresolvable, (
        "these released signal names no longer resolve, so any saved strategy using one "
        "silently evaluates it as False: " + ", ".join(unresolvable)
    )


def test_every_alias_points_at_something_registered():
    dangling = sorted(
        f"{old} -> {new}"
        for old, new in RuleRegistry._aliases.items()
        if new not in RuleRegistry.names()
    )
    assert not dangling, "aliases whose target is not registered: " + ", ".join(dangling)


def test_the_frozen_set_covers_everything_registered_today():
    missing = sorted(set(RuleRegistry.names()) - set(RELEASED_SIGNAL_NAMES))
    assert not missing, (
        "signals registered but absent from RELEASED_SIGNAL_NAMES; add them so a later "
        "rename cannot drop them silently: " + ", ".join(missing)
    )
