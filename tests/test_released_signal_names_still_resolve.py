"""Every signal name that has ever been released still resolves.

Registered names are the strategy-facing contract. A saved strategy stores the name
as a string, so a name that stops resolving does not raise where the strategy lives
-- it raises at evaluation, inside a caller that treats the failure as "the signal
did not fire". A rename is therefore only safe with an alias behind it.

RELEASED_SIGNAL_NAMES is the union of the names registered in every released version
from v1.3.4 onward. Adding an entry is what shipping a new signal looks like. Removing
one is not permitted: retire a name by pointing it at its replacement with
RuleRegistry.alias(old, new), which is what makes this test pass again.

This test exists because the v2.0.0 rename of the four apo_* signals to
macd_line_* shipped without aliases while the chandelier_* and
volatility_stop_* renames in the same release shipped with them. Nothing compared
the alias list against the names already in circulation.
"""

